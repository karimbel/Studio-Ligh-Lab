export const dictionaries: Record<Lang, Record<Key, string>> = { fr, en }
export type TKey = Key

export type Translator = {
  lang: Lang
  setLang: (lang: Lang) => void
  t: (key: TKey, vars?: Record<string, string | number>) => string
  l: (text: L10n) => string
  num: (value: number, digits?: number) => string
}

export const makeTranslator = (lang: Lang, setLang: (lang: Lang) => void): Translator => ({
  lang,
  setLang,
  t: (key, vars) => {
    const template = dictionaries[lang][key] ?? key
    return vars ? template.replace(/\{(\w+)\}/g, (_, name) => String(vars[name] ?? `{${name}}`)) : template
  },
  l: text => text[lang],
  num: (value, digits = 1) => value.toLocaleString(lang === 'fr' ? 'fr-FR' : 'en-GB', { minimumFractionDigits: digits, maximumFractionDigits: digits }),
})

const I18nContext = createContext<Translator>(makeTranslator('fr', () => {}))

export function I18nProvider({ value, children }: { value: Translator; children: ReactNode }) {
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>
}

export const useI18n = () => useContext(I18nContext)

export const detectLang = (): Lang => typeof navigator !== 'undefined' && !navigator.language?.toLowerCase().startsWith('fr') ? 'en' : 'fr'
